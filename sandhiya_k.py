"""## **2) Utilities: Neighbor Lookup + k-hop Subgraph Extraction**

To make the model **subgraph-aware**, we extract a k-hop neighborhood around each target node (paper),
and compute a **subgraph summary embedding** (mean pool across nodes in that local subgraph).
"""

# ==========================================================
# Code Cell: Build adjacency lists for fast neighborhood ops
# ==========================================================

def build_adj_lists(edges: Dict[Tuple[str,str,str], Tuple[torch.Tensor, torch.Tensor]]):
    # adjacency: for each edge type, map src -> list(dst)
    adj = {}
    for etype, (src, dst) in edges.items():
        src = src.tolist()
        dst = dst.tolist()
        d = {}
        for s, t in zip(src, dst):
            d.setdefault(s, []).append(t)
        adj[etype] = d
    return adj

ADJ = build_adj_lists(G.edges)

def k_hop_subgraph_paper(
    paper_id: int,
    k: int = 2,
) -> Dict[str, Set[int]]:
    """
    Extract a k-hop heterogeneous neighborhood around a PAPER node.
    Returns node sets per type: {"paper": set(...), "author": set(...), "venue": set(...)}
    """
    visited = {"paper": set([paper_id]), "author": set(), "venue": set()}
    frontier = {"paper": set([paper_id]), "author": set(), "venue": set()}

    # Define which edge types to traverse from each node type
    # We'll traverse all available edges, but only those matching current node type as src_type.
    all_etypes = list(G.edges.keys())

    for _ in range(k):
        new_frontier = {"paper": set(), "author": set(), "venue": set()}
        for (src_type, rel, dst_type) in all_etypes:
            src_nodes = frontier[src_type]
            if not src_nodes:
                continue
            adj_map = ADJ[(src_type, rel, dst_type)]
            for s in src_nodes:
                if s in adj_map:
                    for t in adj_map[s]:
                        if t not in visited[dst_type]:
                            visited[dst_type].add(t)
                            new_frontier[dst_type].add(t)
        frontier = new_frontier

    return visited

