"""## **3) Subgraph-Aware Heterogeneous Convolution Layer**

We implement a simple, fast heterogeneous message passing block:

For each edge type (src_type, rel, dst_type):
- transform src features with a relation-specific linear map
- aggregate into dst nodes using mean pooling

Then add **subgraph summary**:
- for each paper node, compute pooled embedding from its k-hop neighborhood node features
- inject it into paper representation via gating

This is a lightweight approximation of "subgraph-aware convolution".
"""

# ==========================================
# Code Cell: Hetero Subgraph-Aware GNN Module
# ==========================================

class HeteroConv(nn.Module):
    def __init__(self, feat_dim: int, hidden_dim: int, edge_types: List[Tuple[str,str,str]]):
        super().__init__()
        self.feat_dim = feat_dim
        self.hidden_dim = hidden_dim
        self.edge_types = edge_types

        # Type-specific input projection
        self.type_proj = nn.ModuleDict({
            "paper": nn.Linear(feat_dim, hidden_dim),
            "author": nn.Linear(feat_dim, hidden_dim),
            "venue": nn.Linear(feat_dim, hidden_dim),
        })

        # Relation-specific message transforms
        self.rel_lin = nn.ModuleDict()
        for (s, r, d) in edge_types:
            key = f"{s}__{r}__{d}"
            self.rel_lin[key] = nn.Linear(hidden_dim, hidden_dim, bias=False)

        # Output update per node type
        self.out_lin = nn.ModuleDict({
            "paper": nn.Linear(hidden_dim, hidden_dim),
            "author": nn.Linear(hidden_dim, hidden_dim),
            "venue": nn.Linear(hidden_dim, hidden_dim),
        })

    def forward(self, x_dict: Dict[str, torch.Tensor], edges: Dict[Tuple[str,str,str], Tuple[torch.Tensor, torch.Tensor]]):
        # 1) project inputs by type
        h = {t: F.relu(self.type_proj[t](x)) for t, x in x_dict.items()}

        # 2) initialize aggregations
        agg = {t: torch.zeros_like(h[t]) for t in h.keys()}

        # 3) message passing per edge type (mean aggregation)
        for (src_type, rel, dst_type), (src, dst) in edges.items():
            src = src.to(h[src_type].device)
            dst = dst.to(h[dst_type].device)

            key = f"{src_type}__{rel}__{dst_type}"
            msg = self.rel_lin[key](h[src_type][src])  # [E, hidden]
            # aggregate by dst index (mean)
            agg[dst_type].index_add_(0, dst, msg)

        # 4) normalize by indegree to approximate mean
        for t in agg.keys():
            # compute indegree across all incoming edge types to node type t
            indeg = torch.zeros(agg[t].shape[0], device=agg[t].device)
            for (src_type, rel, dst_type), (src, dst) in edges.items():
                if dst_type != t:
                    continue
                indeg.index_add_(0, dst.to(indeg.device), torch.ones_like(dst, dtype=torch.float, device=indeg.device))
            indeg = indeg.clamp(min=1.0).unsqueeze(1)
            agg[t] = agg[t] / indeg

        # 5) update
        out = {t: F.relu(self.out_lin[t](agg[t] + h[t])) for t in h.keys()}
        return out


class SubgraphAwarePaperEncoder(nn.Module):
    def __init__(self, feat_dim: int, hidden_dim: int, edge_types: List[Tuple[str,str,str]], k_hop: int = 2):
        super().__init__()
        self.k_hop = k_hop
        self.conv1 = HeteroConv(feat_dim, hidden_dim, edge_types)
        self.conv2 = HeteroConv(hidden_dim, hidden_dim, edge_types)

        # Subgraph gating: fuse node embedding with subgraph summary embedding
        self.sg_proj = nn.Linear(hidden_dim, hidden_dim)
        self.gate = nn.Linear(hidden_dim * 2, hidden_dim)

    @torch.no_grad()
    def subgraph_summary_for_papers(self, h_dict: Dict[str, torch.Tensor], paper_ids: torch.Tensor) -> torch.Tensor:
        """
        Compute pooled k-hop subgraph summary for each given paper id.
        Uses current hidden representations h_dict.
        """
        summaries = []
        for pid in paper_ids.tolist():
            nodes = k_hop_subgraph_paper(pid, k=self.k_hop)

            pooled = []
            for t in ["paper", "author", "venue"]:
                if len(nodes[t]) == 0:
                    continue
                idx = torch.tensor(list(nodes[t]), dtype=torch.long, device=h_dict[t].device)
                pooled.append(h_dict[t][idx].mean(dim=0))
            if len(pooled) == 0:
                sg = torch.zeros(h_dict["paper"].shape[1], device=h_dict["paper"].device)
            else:
                sg = torch.stack(pooled, dim=0).mean(dim=0)  # mean over types
            summaries.append(sg)

        return torch.stack(summaries, dim=0)

    def forward(self, x_dict: Dict[str, torch.Tensor], edges: Dict[Tuple[str,str,str], Tuple[torch.Tensor, torch.Tensor]], paper_ids: torch.Tensor):
        # Two hetero conv layers
        h1 = self.conv1(x_dict, edges)
        h2 = self.conv2(h1, edges)

        # paper node embeddings
        paper_h = h2["paper"][paper_ids.to(h2["paper"].device)]

        # subgraph summary computed from h2 (no grad through extraction loop for speed)
        with torch.no_grad():
            sg = self.subgraph_summary_for_papers(h2, paper_ids.to(h2["paper"].device))

        sg = F.relu(self.sg_proj(sg))
        fused = torch.cat([paper_h, sg], dim=1)
        g = torch.sigmoid(self.gate(fused))
        out = g * paper_h + (1 - g) * sg
        return out

"""## **4) Few-Shot Episodes (N-way, K-shot, Q-query**)

We implement episodic sampling over **paper labels**:
- Choose N classes
- For each class: sample K support papers and Q query papers
- Encode papers using subgraph-aware encoder
- Compute class prototypes from support embeddings
- Classify queries by distance to prototypes
"""

# ==========================================
# Code Cell: Episodic Sampler + Prototypical Loss
# ==========================================

def sample_episode(
    y: torch.Tensor,
    candidate_idx: torch.Tensor,
    n_way: int = 5,
    k_shot: int = 5,
    q_query: int = 10
):
    # restrict labels to candidate_idx
    cand = candidate_idx.tolist()
    labels = y[candidate_idx].tolist()
    label_to_nodes = {}
    for nid, lab in zip(cand, labels):
        label_to_nodes.setdefault(int(lab), []).append(int(nid))

    # pick n classes with enough samples
    eligible = [c for c, nodes in label_to_nodes.items() if len(nodes) >= (k_shot + q_query)]
    chosen = random.sample(eligible, k=n_way)

    support_ids, support_labels = [], []
    query_ids, query_labels = [], []

    for i, c in enumerate(chosen):
        nodes = random.sample(label_to_nodes[c], k=k_shot + q_query)
        s = nodes[:k_shot]
        q = nodes[k_shot:]
        support_ids.extend(s)
        support_labels.extend([i] * k_shot)  # remap to 0..n_way-1
        query_ids.extend(q)
        query_labels.extend([i] * q_query)

    return (
        torch.tensor(support_ids, dtype=torch.long),
        torch.tensor(support_labels, dtype=torch.long),
        torch.tensor(query_ids, dtype=torch.long),
        torch.tensor(query_labels, dtype=torch.long),
        chosen
    )

def prototypical_logits(support_emb, support_y, query_emb, n_way: int):
    # compute prototypes
    protos = []
    for c in range(n_way):
        protos.append(support_emb[support_y == c].mean(dim=0))
    protos = torch.stack(protos, dim=0)  # [n_way, d]

    # negative squared euclidean distance
    # logits shape: [num_query, n_way]
    q2 = (query_emb ** 2).sum(dim=1, keepdim=True)
    p2 = (protos ** 2).sum(dim=1).unsqueeze(0)
    dist2 = q2 - 2 * query_emb @ protos.t() + p2
    return -dist2

