def run_episodes(split_idx: torch.Tensor, num_episodes: int, train: bool):
    accs = []
    losses = []
    successful_episodes = 0  # Track successful episodes

    attempted_episodes = 0
    max_attempts = num_episodes * 5  # Allow for multiple attempts to sample an episode

    # Continue sampling until the required number of successful episodes is reached
    # or maximum attempts are exhausted.
    while successful_episodes < num_episodes and attempted_episodes < max_attempts:
        attempted_episodes += 1
        s_ids, s_y, q_ids, q_y, chosen_classes = sample_episode(
            y=y.detach().cpu(),
            candidate_idx=split_idx.detach().cpu(),
            n_way=N_WAY,
            k_shot=K_SHOT,
            q_query=Q_QUERY
        )

        if s_ids is None:  # If sampling failed (not enough eligible classes)
            continue  # Try to sample another episode

        successful_episodes += 1

        s_ids, s_y = s_ids.to(device), s_y.to(device)
        q_ids, q_y = q_ids.to(device), q_y.to(device)

        if train:
            model.train()
            opt.zero_grad()
        else:
            model.eval() # Set model to evaluation mode

        s_emb = model(x_dict, edges, s_ids)
        q_emb = model(x_dict, edges, q_ids)

        logits = prototypical_logits(s_emb, s_y, q_emb, n_way=N_WAY)
        loss = F.cross_entropy(logits, q_y)

        if train:
            loss.backward()
            torch.nn.utils.clip_grad_norm_(model.parameters(), 5.0)
            opt.step()

        pred = logits.argmax(dim=1)
        acc = (pred == q_y).float().mean().item()

        accs.append(acc)
        losses.append(loss.item())

    if successful_episodes == 0: # Handle case where no episodes were successful after all attempts
        print(f"Warning: No episodes were successfully sampled for this split after {max_attempts} attempts.")
        return 0.0, 0.0
    elif successful_episodes < num_episodes:
        print(f"Warning: Only {successful_episodes} out of {num_episodes} episodes were successfully sampled for this split.")

    return float(np.mean(losses)), float(np.mean(accs))


