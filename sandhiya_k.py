@dataclass
class HeteroGraph:
    # Node features by node type: {ntype: Tensor[num_nodes, feat_dim]}
    x: Dict[str, torch.Tensor]
    # Node ids per type: {ntype: list of global node ids} (optional)
    # Edge lists by edge type: {(src_type, rel_type, dst_type): (src_idx_tensor, dst_idx_tensor)}
    edges: Dict[Tuple[str, str, str], Tuple[torch.Tensor, torch.Tensor]]
    # Labels for a specific node type (here: "paper")
    y: torch.Tensor  # [num_papers]
    # Masks (indices) for train/val/test papers
    train_idx: torch.Tensor
    val_idx: torch.Tensor
    test_idx: torch.Tensor


def make_synthetic_hetero_graph(
    num_papers=400,
    num_authors=200,
    num_venues=30,
    feat_dim=32,
    num_classes=6,
    cites_per_paper=5,
    authors_per_paper=(1, 4),
    papers_per_author=(2, 8),
) -> HeteroGraph:
    # ---- node features ----
    x = {
        "paper": torch.randn(num_papers, feat_dim),
        "author": torch.randn(num_authors, feat_dim),
        "venue": torch.randn(num_venues, feat_dim),
    }

    # ---- paper labels (synthetic) ----
    # Create mild cluster structure: class centroids add signal to paper features
    centroids = torch.randn(num_classes, feat_dim) * 1.5
    y = torch.randint(0, num_classes, (num_papers,))
    x["paper"] += centroids[y] * 0.8

    edges = {}

    def add_edges(src_type, rel, dst_type, src_list, dst_list):
        key = (src_type, rel, dst_type)
        src_t = torch.tensor(src_list, dtype=torch.long)
        dst_t = torch.tensor(dst_list, dtype=torch.long)
        edges[key] = (src_t, dst_t)

    # ---- author -> paper (writes) ----
    a2p_src, a2p_dst = [], []
    # First decide papers written by each author
    author_papers = []
    for a in range(num_authors):
        k = random.randint(papers_per_author[0], papers_per_author[1])
        author_papers.append(random.sample(range(num_papers), k=min(k, num_papers)))

    # Also ensure each paper has at least 1 author
    paper_authors = [[] for _ in range(num_papers)]
    for a, plist in enumerate(author_papers):
        for p in plist:
            paper_authors[p].append(a)

    for p in range(num_papers):
        if len(paper_authors[p]) == 0:
            paper_authors[p].append(random.randrange(num_authors))

        # Optionally cap authors per paper
        cap = random.randint(authors_per_paper[0], authors_per_paper[1])
        if len(paper_authors[p]) > cap:
            paper_authors[p] = random.sample(paper_authors[p], cap)

        for a in paper_authors[p]:
            a2p_src.append(a)
            a2p_dst.append(p)

    add_edges("author", "writes", "paper", a2p_src, a2p_dst)
    add_edges("paper", "rev_writes", "author", a2p_dst, a2p_src)

    # ---- paper -> venue (published_in) ----
    p2v_src, p2v_dst = [], []
    # Make class-dependent venue preferences (adds hetero signal)
    class_venue_pref = [random.sample(range(num_venues), k=max(3, num_venues // 6)) for _ in range(num_classes)]
    for p in range(num_papers):
        c = int(y[p].item())
        v = random.choice(class_venue_pref[c])
        p2v_src.append(p)
        p2v_dst.append(v)
    add_edges("paper", "published_in", "venue", p2v_src, p2v_dst)
    add_edges("venue", "rev_published_in", "paper", p2v_dst, p2v_src)

    # ---- paper -> paper (cites) ----
    p2p_src, p2p_dst = [], []
    for p in range(num_papers):
        # bias citations slightly toward same class
        same_class = [q for q in range(num_papers) if q != p and y[q].item() == y[p].item()]
        other = [q for q in range(num_papers) if q != p and y[q].item() != y[p].item()]
        picks = []
        for _ in range(cites_per_paper):
            if random.random() < 0.65 and len(same_class) > 0:
                picks.append(random.choice(same_class))
            else:
                picks.append(random.choice(other))
        for q in picks:
            p2p_src.append(p)
            p2p_dst.append(q)
    add_edges("paper", "cites", "paper", p2p_src, p2p_dst)
    add_edges("paper", "rev_cites", "paper", p2p_dst, p2p_src)

    # ---- train/val/test split over papers ----
    idx = np.arange(num_papers)
    np.random.shuffle(idx)
    n_train = int(0.7 * num_papers)
    n_val = int(0.1 * num_papers)
    train_idx = torch.tensor(idx[:n_train], dtype=torch.long)
    val_idx = torch.tensor(idx[n_train:n_train+n_val], dtype=torch.long)
    test_idx = torch.tensor(idx[n_train+n_val:], dtype=torch.long)

    return HeteroGraph(x=x, edges=edges, y=y, train_idx=train_idx, val_idx=val_idx, test_idx=test_idx)


